#!/usr/bin/env python3
"""Streamlit dashboard for SRS-aligned bearing diagnosis."""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
CACHE = ROOT / ".cache"
CACHE.mkdir(exist_ok=True)
os.environ.setdefault("MPLCONFIGDIR", str(CACHE / "matplotlib"))
os.environ.setdefault("XDG_CACHE_HOME", str(CACHE))
os.environ.setdefault("MPLBACKEND", "Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import streamlit as st

from inference import analyze_signal, read_signal
from model_registry import discover_registry


st.set_page_config(page_title="Bearing Health", layout="wide")
st.title("Bearing Fault Diagnosis")
st.caption("CWRU laboratory benchmark — not validated for ceiling-fan motors")


def available_models(task):
    entries, rejected = discover_registry()
    models = sorted({entry["model_family"] for entry in entries if entry["task"] == task})
    return models, rejected


def render_model_evidence(result):
    """Render validation and feature evidence generated by the ML pipeline."""
    task = result.task
    model = result.model_family
    importance_path = ROOT / "results/feature_importance_top.csv"
    metrics_path = ROOT / "results/fold_metrics.csv"
    confusion_path = ROOT / f"results/confusion_{task}_leave_one_load_out_{model}.png"

    with st.expander("Model explanation and performance", expanded=False):
        entries, _ = discover_registry()
        selected = next((entry for entry in entries if entry["task"] == task and entry["model_family"] == model), None)
        if selected:
            validation = selected.get("validation", {})
            cv_scores = validation.get("cv_macro_f1", {})
            metadata = pd.DataFrame([
                ["Artifact", selected["artifact"]],
                ["Feature version", selected["feature_version"]],
                ["Feature count", selected["feature_count"]],
                ["Window size", selected["window_size"]],
                ["Target sampling rate", f"{selected['target_sampling_rate']:,} Hz"],
                ["Validation scheme", validation.get("selection_scheme", "not recorded")],
                ["LOLO macro-F1", cv_scores.get(model, "not recorded")],
            ], columns=["Property", "Value"])
            st.write("Selected artifact metadata")
            st.dataframe(metadata, use_container_width=True, hide_index=True)

        if importance_path.exists():
            importance = pd.read_csv(importance_path)
            matching = importance[(importance.task == task) & (importance.model == model)]
            if not matching.empty:
                st.write("Mean feature importance from the evaluated tree models.")
                chart = matching.set_index("feature")["permutation_importance"].sort_values()
                st.bar_chart(chart)
                st.dataframe(
                    matching[["feature", "native_importance", "permutation_importance"]]
                    .sort_values("permutation_importance", ascending=False),
                    use_container_width=True,
                    hide_index=True,
                )
            else:
                st.info("No feature-importance rows are available for this task/model.")
        else:
            st.info("Feature-importance output has not been generated.")

        if metrics_path.exists():
            metrics = pd.read_csv(metrics_path)
            matching = metrics[(metrics.task == task) & (metrics.model == model) &
                               (metrics.scheme == "leave_one_load_out")]
            if not matching.empty:
                metric_names = [
                    "balanced_accuracy", "macro_f1", "accuracy_not_headline",
                    "inference_ms_per_window", "training_time_seconds",
                ]
                summary = pd.DataFrame({
                    "metric": [name for name in metric_names if name in matching],
                    "mean": [matching[name].mean() for name in metric_names if name in matching],
                    "std": [matching[name].std() for name in metric_names if name in matching],
                })
                st.write("Leave-One-Load-Out benchmark summary")
                st.dataframe(summary, use_container_width=True, hide_index=True)
                st.caption("These are CWRU benchmark measurements, not field-performance guarantees.")
            else:
                st.info("No Leave-One-Load-Out metrics are available for this task/model.")

        if confusion_path.exists():
            st.image(str(confusion_path), caption=f"{task} / {model} / Leave-One-Load-Out confusion matrix")


def render_limitations(result):
    with st.expander("Data quality and limitations", expanded=False):
        if result.warnings:
            for warning in result.warnings:
                st.warning(warning)
        else:
            st.success("Input passed numeric, finite-value, and minimum-length checks.")
        st.write(
            "The input was processed using the saved CWRU assumptions: Drive-End vibration, "
            "12 kHz target rate, 2048-sample non-overlapping windows, and incomplete-tail discard."
        )
        st.write(
            "Health Index is 100 × model probability of Healthy. It is a model-derived indicator, "
            "not remaining useful life, exact lifetime, calibrated maintenance risk, or a safety guarantee."
        )
        st.write(
            "The models were trained and validated on controlled CWRU laboratory recordings. "
            "Ceiling-fan or other field equipment requires separate validation."
        )


if "diagnosis_result" not in st.session_state:
    st.session_state.diagnosis_result = None


source = st.radio("1. Signal source", ["Upload", "CWRU sample"], horizontal=True)
task_label = st.radio("2. Classification task", ["Binary", "Multiclass"], horizontal=True)
task = task_label.lower()
models, rejected = available_models(task)

if rejected:
    st.warning(f"Some model artifacts were rejected by compatibility checks: {rejected}")
if not models:
    st.error(f"No compatible saved model is available for the {task} task.")
    st.stop()

model = st.selectbox("3. Compatible model", models, format_func=lambda value: {
    "rf": "Random Forest",
    "svm": "SVM",
    "xgboost": "XGBoost",
}.get(value, value))
st.info(
    "Upload a numeric CSV, NPY, or MAT vibration signal with at least 2,048 samples. "
    "For CSV/NPY inputs, select whether the source rate is 12 kHz or 48 kHz. "
    "The selected model is applied after the signal is normalized to 12 kHz."
)

signal = None
sampling_rate = None
input_name = None

try:
    if source == "Upload":
        upload = st.file_uploader(
            "Upload a numeric vibration signal",
            type=["csv", "mat", "npy"],
            help="Minimum 2048 samples. CSV and NPY inputs require a sampling-rate selection.",
        )
        sampling_rate = st.selectbox("Input sampling rate", [12000, 48000], format_func=lambda value: f"{value:,} Hz")
        if upload is not None:
            input_name = upload.name
            signal = read_signal(upload, upload.name)
    else:
        manifest = pd.read_csv(ROOT / "docs/data_manifest.csv", dtype={"file_id": str})
        file_id = st.selectbox("CWRU recording", manifest.file_id)
        item = manifest.loc[manifest.file_id == file_id].iloc[0]
        input_name = item.filename
        path = ROOT / "data/raw" / item.filename
        signal = read_signal(path, item.filename, item.channel)
        sampling_rate = int(item.source_sampling_rate)

    action_col, reset_col = st.columns([3, 1])
    run_diagnosis = signal is not None and action_col.button("4. Run diagnosis", type="primary")
    reset_diagnosis = reset_col.button("Reset result")
    if reset_diagnosis:
        st.session_state.diagnosis_result = None
    if run_diagnosis:
        st.session_state.diagnosis_result = analyze_signal(
            signal, sampling_rate, task, model_family=model, filename=input_name
        )

    result = st.session_state.diagnosis_result
    if result is not None:
        if result.task != task or result.model_family != model:
            st.info("The displayed result belongs to a previous task/model selection. Run diagnosis to refresh it.")

        condition, fault = None, None
        if result.task == "binary":
            condition = result.predicted_class
        else:
            fault = result.predicted_class

        cards = st.columns(5 if result.health_index is not None else 4)
        cards[0].metric("Task", result.task.title())
        cards[1].metric("Model", result.model_family.upper())
        cards[2].metric("Prediction", condition or fault)
        cards[3].metric("Probability", f"{result.confidence:.1%}")
        if result.health_index is not None:
            cards[4].metric("Health Index", f"{result.health_index:.0f}/100")

        st.subheader("Class probabilities")
        probability_frame = pd.DataFrame({"class": list(result.probabilities), "probability": list(result.probabilities.values())})
        st.bar_chart(probability_frame.set_index("class"), y="probability")
        st.dataframe(probability_frame, use_container_width=True, hide_index=True)

        st.subheader("Signal evidence")
        fig, axes = plt.subplots(1, 2, figsize=(12, 3.5))
        first = np.asarray(result.first_window)
        axes[0].plot(np.arange(len(first)) / result.processed_sampling_rate, first, linewidth=.7)
        axes[0].set(title="First analyzed 2048-sample window", xlabel="Seconds", ylabel="Amplitude")
        spectrum = np.abs(np.fft.rfft(first * np.hanning(len(first))))
        axes[1].plot(np.fft.rfftfreq(len(first), 1 / result.processed_sampling_rate), spectrum, linewidth=.7)
        axes[1].set(title="FFT", xlabel="Hz", ylabel="Amplitude")
        fig.tight_layout()
        st.pyplot(fig)
        plt.close(fig)

        st.subheader("Processing information")
        processing = pd.DataFrame([
            ["Input file", result.input_filename],
            ["Source sampling rate", f"{result.source_sampling_rate:,} Hz"],
            ["Processed sampling rate", f"{result.processed_sampling_rate:,} Hz"],
            ["Signal duration", f"{result.duration_seconds:.4f} s"],
            ["Window size", result.window_size],
            ["Valid windows analyzed", result.valid_window_count],
            ["Discarded tail samples", result.discarded_tail_samples],
        ], columns=["Property", "Value"])
        st.dataframe(processing, use_container_width=True, hide_index=True)

        with st.expander("Key extracted features", expanded=False):
            feature_frame = pd.DataFrame({"feature": list(result.first_window_features), "value": list(result.first_window_features.values())})
            st.dataframe(feature_frame, use_container_width=True, hide_index=True)

        with st.expander("Window-level decisions", expanded=False):
            window_rows = []
            for index, (prediction, probabilities) in enumerate(
                zip(result.window_predictions, result.window_probabilities), start=1
            ):
                row = {"window": index, "prediction": prediction}
                row.update({f"probability_{name}": value for name, value in probabilities.items()})
                window_rows.append(row)
            st.dataframe(pd.DataFrame(window_rows), use_container_width=True, hide_index=True)

        render_model_evidence(result)
        render_limitations(result)
except Exception as error:
    st.error(f"Diagnosis could not be completed: {error}")
